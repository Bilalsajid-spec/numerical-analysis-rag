# Purpose: evaluate retrieval and generated answers against the local PDF collection.
# Work: check source coverage and unrelated-question refusals, and optionally save demo answers.

import argparse
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))
from rag_nm.config import DATA_DIR, PROJECT_ROOT
from rag_nm.retrieval import retrieve, load_manifest
from rag_nm.pipeline import ask
from rag_nm.generation import LocalGenerator


def main():
    parser = argparse.ArgumentParser(description="Evaluate the real local RAG project")
    parser.add_argument("--generate", action="store_true", help="Also generate real answers and DEMO_OUTPUT.md")
    args = parser.parse_args()
    fixture = json.loads((PROJECT_ROOT / "examples" / "questions.json").read_text(encoding="utf-8"))
    results = []
    for case in fixture["questions"]:
        result = retrieve(case["question"])
        wanted = case["week"]
        found = [hit["source"] for hit in result["hits"]]
        passed = not result["supported"] if wanted is None else result["supported"] and f"Week_{wanted}_Numerical_Analysis.pdf" in found
        results.append(dict(case, passed=bool(passed), supported=result["supported"], sources=found, similarity=result["best_similarity"]))
        print(f"{'PASS' if passed else 'FAIL'}: {case['question']}", flush=True)
    report = {"index": load_manifest(), "passed": sum(r["passed"] for r in results), "total": len(results), "results": results}
    (DATA_DIR / "evaluation.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(f"Retrieval/refusal checks: {report['passed']}/{report['total']}")
    if args.generate:
        questions = ["What is relative error and its formula?", "Explain the bisection method and its midpoint formula.",
                     "Explain the Jacobi iterative update formula.", "How do I cook chicken biryani?"]
        output = ["# Actual local RAG output", "", "Generated by the project's local Qwen model using the indexed PDFs. These are actual run results; review the cited PDF pages when checking mathematics.", ""]
        generated = []
        with LocalGenerator() as generator:
            for question in questions:
                result = ask(question, generator)
                generated.append(result)
                output += [f"## {question}", "", result["answer"], "", f"Mode: `{result['mode']}`", "", "Retrieved sources:", ""]
                for i, hit in enumerate(result["sources"], 1):
                    output.append(f"- [{i}] {hit['source']}, PDF page {hit['page']}")
                output.append("")
                print(f"Generated demo: {question}", flush=True)
        (PROJECT_ROOT / "DEMO_OUTPUT.md").write_text("\n".join(output), encoding="utf-8")
        (DATA_DIR / "demo_results.json").write_text(json.dumps(generated, ensure_ascii=False, indent=2), encoding="utf-8")
        print("Actual generated answers saved to DEMO_OUTPUT.md")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
